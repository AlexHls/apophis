def cell_volumes(data_file):
    dx = np.diff(data_file.xf, axis=1)
    dy = np.diff(data_file.yf, axis=1)
    dz = np.diff(data_file.zf, axis=1)
    return dz[:, :, None, None] * dy[:, None, :, None] * dx[:, None, None, :]


def radial_profiles(data_file, nbins=80):
    zz, yy, xx = data_file.GetVolumeLocations(flatten=False)
    prim = data_file.Get("prim", flatten=False)

    rho = prim[:, 0, :, :, :]
    vx = prim[:, 1, :, :, :]
    vy = prim[:, 2, :, :, :]
    vz = prim[:, 3, :, :, :]
    pressure = prim[:, 4, :, :, :]

    radius = np.sqrt(xx**2 + yy**2 + zz**2)
    radial_velocity = np.zeros_like(radius)
    nonzero_radius = radius > 0.0
    radial_velocity[nonzero_radius] = (
        vx[nonzero_radius] * xx[nonzero_radius]
        + vy[nonzero_radius] * yy[nonzero_radius]
        + vz[nonzero_radius] * zz[nonzero_radius]
    ) / radius[nonzero_radius]
    entropy = pressure / rho**GAMMA
    weights = cell_volumes(data_file)

    r_flat = (radius / RADIUS).ravel()
    w_flat = weights.ravel()
    valid = (r_flat > 0.0) & np.isfinite(r_flat) & np.isfinite(w_flat) & (w_flat > 0.0)
    r_min = max(np.min(r_flat[valid]), 1.0e-3)
    r_max = min(np.max(r_flat[valid]), 2.0)
    edges = np.geomspace(r_min, r_max, nbins + 1)
    centers = np.sqrt(edges[:-1] * edges[1:])
    which = np.digitize(r_flat, edges) - 1

    profiles = {"r_over_R": centers}
    for name, values in [
        ("rho", rho),
        ("vr", radial_velocity),
        ("entropy", entropy),
    ]:
        values_flat = values.ravel()
        good = valid & (which >= 0) & (which < nbins) & np.isfinite(values_flat)
        if name != "vr":
            good &= values_flat > 0.0
        weighted_sum = np.bincount(
            which[good], weights=values_flat[good] * w_flat[good], minlength=nbins
        )
        weight_sum = np.bincount(which[good], weights=w_flat[good], minlength=nbins)
        profile = np.full(nbins, np.nan)
        populated = weight_sum > 0.0
        profile[populated] = weighted_sum[populated] / weight_sum[populated]
        profiles[name] = profile

    return profiles


